/** baseHeroId → intrinsic attributes, built once at module load. */
const CHAMPION_STATIC_MAP: ReadonlyMap<number, ChampionStaticRecord> = new Map(
  // Map each packed row to a typed entry; the tuple order matches CHAMPION_STATIC_ROWS.
  CHAMPION_STATIC_ROWS.map(([baseHeroId, rarity, affinity, name]) => [
    baseHeroId,
    { rarity: rarity as RankValue, affinity, name },
  ]),
)

/**
 * Look up a champion's intrinsic attributes by base hero id. Returns `undefined` when
 * the id is missing/invalid or absent from the static table (e.g. a champion newer than
 * the source DBs) — callers then fall back to whatever the live row provided.
 */
export function championStaticRecord(baseHeroId?: number | null): ChampionStaticRecord | undefined {
  // Guard non-finite / non-positive ids so the Map lookup stays clean.
  if (baseHeroId === undefined || baseHeroId === null) return undefined
  const numeric = Number(baseHeroId)
  if (!Number.isFinite(numeric) || numeric <= 0) return undefined
  return CHAMPION_STATIC_MAP.get(numeric)
}
