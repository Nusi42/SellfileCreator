#!/usr/bin/env node
// Generates TS and Rust constants for the minified wasm rule wire format from
// the shared SSOT at shared/wasm-rule-wire-fields.json.
//
// Why minify? compute_merged_rules_value passes ~45k × 29-field rules across
// the wasm boundary on realistic workloads — ~27 MB of JSON dominated by long
// property names (RecipeID, __safeguardPlaceholderMissing, etc).  Shortening
// keys to 1-5 chars cuts the payload by ~10 MB per call and dramatically
// reduces allocator pressure (which manifested as talc deallocate OOB crashes).
//
// Outputs:
//   src/lib/generated/wasmRuleWireFields.ts       — TS field maps + helpers
//   wasm/rule_engine_core/src/generated_wasm_rule_wire_fields.rs
//                                                  — Rust field name consts
//                                                    (used by a consistency
//                                                    test that guards against
//                                                    drift between the TS
//                                                    minify/expand helpers and
//                                                    the Rust RuleRawWire
//                                                    #[serde(rename)] attrs)
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

// Resolve the repo root deterministically so the script works from any CWD.
const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = path.resolve(SCRIPT_DIR, '..', '..')

const SPEC_PATH = path.join(REPO_ROOT, 'shared', 'wasm-rule-wire-fields.json')
const TS_OUT_PATH = path.join(REPO_ROOT, 'src', 'lib', 'generated', 'wasmRuleWireFields.ts')
const RUST_OUT_PATH = path.join(
  REPO_ROOT,
  'wasm',
  'rule_engine_core',
  'src',
  'generated_wasm_rule_wire_fields.rs',
)

const rawSpec = await fs.readFile(SPEC_PATH, 'utf8')
const spec = JSON.parse(rawSpec)

// Strip the documentation field from the spec before iterating.
const sections = Object.fromEntries(
  Object.entries(spec).filter(([key]) => !key.startsWith('_')),
)

// Validate uniqueness of short names within each section so drift fails early.
for (const [sectionName, mapping] of Object.entries(sections)) {
  const seen = new Map()
  for (const [long, short] of Object.entries(mapping)) {
    if (seen.has(short)) {
      throw new Error(
        `Short alias "${short}" collides in section ${sectionName}: ${seen.get(short)} and ${long}`,
      )
    }
    seen.set(short, long)
  }
}

// ── TS output ────────────────────────────────────────────────────────────

const tsLines = []
tsLines.push(
  '// AUTO-GENERATED by scripts/tooling/generate-wasm-rule-wire-fields.mjs',
)
tsLines.push('// DO NOT EDIT DIRECTLY.  Update shared/wasm-rule-wire-fields.json and re-run the generator.')
tsLines.push(
  '// This file defines the minified wire format used by compute_merged_rules_value',
)
tsLines.push('// to keep the wasm-boundary payload small on 45k-rule workloads.')
tsLines.push('')

// Emit each section as a Record<long, short>.
for (const [sectionName, mapping] of Object.entries(sections)) {
  tsLines.push(`export const ${sectionName}_LONG_TO_SHORT = {`)
  for (const [long, short] of Object.entries(mapping)) {
    // JSON.stringify correctly escapes quotes / special characters in identifiers.
    tsLines.push(`  ${JSON.stringify(long)}: ${JSON.stringify(short)},`)
  }
  tsLines.push('} as const')
  tsLines.push('')
}

// Inverse maps for expanding WASM output back to long-named objects.
for (const sectionName of Object.keys(sections)) {
  tsLines.push(
    `export const ${sectionName}_SHORT_TO_LONG: Record<string, string> = Object.fromEntries(`,
  )
  tsLines.push(
    `  Object.entries(${sectionName}_LONG_TO_SHORT).map(([long, short]) => [short, long]),`,
  )
  tsLines.push(')')
  tsLines.push('')
}

// Generic translation helpers.  These walk an object once and rename keys per
// the supplied map.  Undeclared keys pass through untouched so evolving shapes
// do not require a generator rerun for every field addition.
tsLines.push('// Build a new object with top-level keys renamed via the supplied map.')
tsLines.push('// Undeclared keys pass through unchanged; values are NOT cloned (alias).')
tsLines.push(
  'const renameKeys = <T extends object>(source: T, map: Readonly<Record<string, string>>): Record<string, unknown> => {',
)
tsLines.push('  const out: Record<string, unknown> = {}')
tsLines.push('  for (const key in source) {')
tsLines.push('    if (!Object.prototype.hasOwnProperty.call(source, key)) continue')
tsLines.push('    const mapped = map[key] ?? key')
tsLines.push('    out[mapped] = (source as Record<string, unknown>)[key]')
tsLines.push('  }')
tsLines.push('  return out')
tsLines.push('}')
tsLines.push('')

// Specialised helpers for RuleRaw that also translate the nested Substats
// (RuleSubRaw) array, since Rust serialises that as short keys too.  These
// are the only helpers call sites need; keep renameKeys private above.
tsLines.push('// Minify a RuleRaw-shaped object (HsfRule / HsfRuleWithRecipe) to the short-key')
tsLines.push('// wire form.  Nested Substats array is also minified via the RuleSubRaw map.')
tsLines.push('export const minifyRuleRawForWire = (rule: object): Record<string, unknown> => {')
tsLines.push('  const top = renameKeys(rule, RuleRaw_LONG_TO_SHORT)')
tsLines.push('  // Substats needs its own field map; Rust uses RuleSubRawWire there.')
tsLines.push(
  '  const substatsShortKey = RuleRaw_LONG_TO_SHORT.Substats',
)
tsLines.push('  const subs = top[substatsShortKey]')
tsLines.push('  if (Array.isArray(subs)) {')
tsLines.push(
  '    top[substatsShortKey] = subs.map((sub) => renameKeys(sub as object, RuleSubRaw_LONG_TO_SHORT))',
)
tsLines.push('  }')
tsLines.push('  return top')
tsLines.push('}')
tsLines.push('')
tsLines.push('// Expand a short-key wire RuleRaw back to the long-key canonical form.')
tsLines.push('// Reverse of minifyRuleRawForWire — handles the nested Substats array too.')
tsLines.push('export const expandRuleRawFromWire = (rule: object): Record<string, unknown> => {')
tsLines.push('  const top = renameKeys(rule, RuleRaw_SHORT_TO_LONG)')
tsLines.push('  const subs = top.Substats')
tsLines.push('  if (Array.isArray(subs)) {')
tsLines.push(
  '    top.Substats = subs.map((sub) => renameKeys(sub as object, RuleSubRaw_SHORT_TO_LONG))',
)
tsLines.push('  }')
tsLines.push('  return top')
tsLines.push('}')
tsLines.push('')

// Specialised helper for artifact rows (store_artifact_rows_value). The shape
// has three nested levels:
//   row → SafeguardCollectRowFastIn
//     row.artifact → SafeguardWasmArtifactRawIn
//       row.artifact.substats → SafeguardWasmSubstatRawIn[]
//       row.artifact.gearInspectorItem → TestItemRaw
//       row.artifact.mainStat → may be a number (not an object) — leave alone
//     row.item → TestItemRaw (optional, usually absent for store path)
tsLines.push('// Minify a SafeguardCollectRowFastIn artifact row to the wire form.  Handles')
tsLines.push('// nested SafeguardWasmArtifactRawIn (+ its Substats and gearInspectorItem),')
tsLines.push('// and optional top-level item (TestItemRaw).  Used by storeArtifactRows path.')
tsLines.push('export const minifySafeguardCollectRowFastInForWire = (row: object): Record<string, unknown> => {')
tsLines.push('  const top = renameKeys(row, SafeguardCollectRowFastIn_LONG_TO_SHORT)')
tsLines.push('  const artifactShortKey = SafeguardCollectRowFastIn_LONG_TO_SHORT.artifact')
tsLines.push('  const artifact = top[artifactShortKey]')
tsLines.push('  if (artifact && typeof artifact === "object") {')
tsLines.push('    const artifactMin = renameKeys(artifact as object, SafeguardWasmArtifactRawIn_LONG_TO_SHORT)')
tsLines.push('    // Substats inside artifact: array of SafeguardWasmSubstatRawIn.')
tsLines.push('    const substatsShortKey = SafeguardWasmArtifactRawIn_LONG_TO_SHORT.substats')
tsLines.push('    const subs = artifactMin[substatsShortKey]')
tsLines.push('    if (Array.isArray(subs)) {')
tsLines.push('      artifactMin[substatsShortKey] = subs.map((sub) => renameKeys(sub as object, SafeguardWasmSubstatRawIn_LONG_TO_SHORT))')
tsLines.push('    }')
tsLines.push('    // gearInspectorItem inside artifact: single TestItemRaw object.')
tsLines.push('    const giiShortKey = SafeguardWasmArtifactRawIn_LONG_TO_SHORT.gearInspectorItem')
tsLines.push('    const gii = artifactMin[giiShortKey]')
tsLines.push('    if (gii && typeof gii === "object") {')
tsLines.push('      artifactMin[giiShortKey] = renameKeys(gii as object, TestItemRaw_LONG_TO_SHORT)')
tsLines.push('    }')
tsLines.push('    top[artifactShortKey] = artifactMin')
tsLines.push('  }')
tsLines.push('  // Optional top-level item (rarely set from TS store path, but handle anyway).')
tsLines.push('  const itemShortKey = SafeguardCollectRowFastIn_LONG_TO_SHORT.item')
tsLines.push('  const item = top[itemShortKey]')
tsLines.push('  if (item && typeof item === "object") {')
tsLines.push('    top[itemShortKey] = renameKeys(item as object, TestItemRaw_LONG_TO_SHORT)')
tsLines.push('  }')
tsLines.push('  return top')
tsLines.push('}')
tsLines.push('')

// ── Rust output ──────────────────────────────────────────────────────────

const rustLines = []
rustLines.push('// AUTO-GENERATED by scripts/tooling/generate-wasm-rule-wire-fields.mjs')
rustLines.push('// DO NOT EDIT DIRECTLY.  Update shared/wasm-rule-wire-fields.json and re-run the generator.')
rustLines.push('//')
rustLines.push('// These constants document the wire-format field names used by compute_merged_rules_value.')
rustLines.push("// The actual #[serde(rename)] attrs on RuleRawWire / RuleSubRawWire / ComputeMergedRulesInWire")
rustLines.push("// are hand-written, and a Rust unit test uses these constants to verify the two stay in sync.")
rustLines.push('')

// Convert snake_case section name for Rust constant naming convention.
const toScreamingSnake = (camel) =>
  camel.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase()

for (const [sectionName, mapping] of Object.entries(sections)) {
  const constName = toScreamingSnake(sectionName)
  const pairs = Object.entries(mapping)
    .map(([long, short]) => `    ("${long}", "${short}"),`)
    .join('\n')
  rustLines.push(`pub const ${constName}_FIELD_MAP: &[(&str, &str)] = &[`)
  rustLines.push(pairs)
  rustLines.push('];')
  rustLines.push('')
}

// Ensure output directories exist before writing.
await fs.mkdir(path.dirname(TS_OUT_PATH), { recursive: true })
await fs.mkdir(path.dirname(RUST_OUT_PATH), { recursive: true })

await fs.writeFile(TS_OUT_PATH, `${tsLines.join('\n')}\n`, 'utf8')
await fs.writeFile(RUST_OUT_PATH, `${rustLines.join('\n')}\n`, 'utf8')

console.log(`Generated ${path.relative(REPO_ROOT, TS_OUT_PATH)}`)
console.log(`Generated ${path.relative(REPO_ROOT, RUST_OUT_PATH)}`)
