import type { SxProps, Theme } from '@mui/material/styles'
import { BUILDER_STATUS_CHIP_HEIGHT_PX, STATUS_CHIP_BORDER_RADIUS_PX } from '../lib/constants'
import { resolveDisabledOpacity } from './disabledOpacity'
import { TINT } from '../lib/colorTints'

interface BuilderStatusChipOptions {
  dimDisabled?: boolean
}

// Shared builder status chip styling so the Builder panel and cheat sheet stay visually aligned.
export function createBuilderStatusChipSx(theme: Theme) {
  const chipActiveBg = TINT.success18
  const chipActiveBgHover = TINT.success24
  // text.disabledChannel is not generated by MUI v9; use text.primaryChannel (same RGB channels
  // as text.primary, just at varying alpha) and text.disabled (already carries the right per-scheme alpha).
  const chipDisabledBg = (theme.vars?.palette.action.disabledBackground ?? theme.palette.action.disabledBackground) ?? TINT.textPrimary12
  const chipDisabledColor = (theme.vars?.palette.text.disabled ?? theme.palette.text.disabled)
  // Keep the base opacity aligned with shared disabled UI dimming.
  const baseDisabledOpacity = resolveDisabledOpacity(theme)

  return (enabled: boolean, opts?: BuilderStatusChipOptions): SxProps<Theme> => {
    const shouldDimDisabled = Boolean(opts?.dimDisabled)
    const disabledOpacity = shouldDimDisabled ? baseDisabledOpacity : 1
    // text.disabled carries the correct per-scheme alpha; alpha() would leave it unchanged anyway.
    const dimmedDisabledColor = chipDisabledColor
    const dimmedDisabledIconColor = shouldDimDisabled
      ? `rgba(var(--mui-palette-text-primaryChannel) / ${Math.min(baseDisabledOpacity * 0.8, 0.5)})`
      : chipDisabledColor
    const dimmedDisabledBg = shouldDimDisabled ? TINT.textPrimary08 : chipDisabledBg

    const borderRadius = `${STATUS_CHIP_BORDER_RADIUS_PX}px`
    return {
      height: BUILDER_STATUS_CHIP_HEIGHT_PX,
      minHeight: BUILDER_STATUS_CHIP_HEIGHT_PX,
      fontWeight: theme.typography.fontWeightMedium ?? 500,
      px: 0,
      backgroundColor: enabled ? chipActiveBg : dimmedDisabledBg,
      // success.light gives the right readable tint on dark surfaces (matches the original dark-only behavior).
      color: enabled ? (theme.vars?.palette.success.light ?? theme.palette.success.light) : dimmedDisabledColor,
      borderRadius,
      overflow: 'hidden',
      '& .MuiChip-icon': {
        color: enabled ? (theme.vars?.palette.success.light ?? theme.palette.success.light) : dimmedDisabledIconColor,
      },
      '& .MuiChip-label': {
        px: theme.spacing(0.75),
        fontWeight: theme.typography.fontWeightMedium ?? 500,
        borderRadius,
      },
      '&.MuiChip-clickable:hover': enabled ? {
        backgroundColor: chipActiveBgHover,
      } : {},
      '&.MuiChip-clickable:active': enabled ? {
        backgroundColor: chipActiveBgHover,
      } : {},
      '&.Mui-focusVisible': enabled ? {
        outline: `2px solid ${TINT.success50}`,
        outlineOffset: 2,
      } : {},
      '&.Mui-disabled': {
        opacity: disabledOpacity,
        backgroundColor: dimmedDisabledBg,
        color: dimmedDisabledColor,
      },
    }
  }
}
