/**
 * gear-db-fixtures — committed RSL Helper gear databases as plain SQL.
 *
 * Real RSL Helper `.db` exports carry far more than the importer reads: the player id
 * (`CBLoot.UMID`), hand-typed team names, battle logs, clan-boss loot history, and so on.
 * Fixtures therefore live in the repo as SQL dumps that keep ONLY the tables the gear
 * importer reads (src/lib/importers/gearDbImporter.ts); every other table is dropped. The
 * kept tables are byte-for-byte as exported except the `Champs` table, whose champions
 * lose their identity (type, name, level, stats, …) on dump: see roster-anonymizer.mjs.
 * Tests build the binary `.db` on demand into a gitignored cache.
 *
 * Layout:
 *   committed dump : tests/fixtures/gear-db/<name>.sql
 *   built database : tmp/fixtures/gear-db/<name>.db   (gitignored, rebuilt when stale)
 *
 * CLI:
 *   node scripts/test/gear-db-fixtures.mjs dump <source.db> <name>   # write + verify a dump
 *   node scripts/test/gear-db-fixtures.mjs build [<name>...]          # default: all fixtures
 *   node scripts/test/gear-db-fixtures.mjs anonymize [<name>...]      # re-dump committed fixtures
 *                                                                     # through the anonymizer
 */
import fs from 'node:fs'
import path from 'node:path'
import { DatabaseSync } from 'node:sqlite'
import { fileURLToPath } from 'node:url'
import { anonymizeGearDbChampions } from './roster-anonymizer.mjs'

// Repo root = cwd; all npm scripts and Playwright specs run from the repo root.
const ROOT = process.cwd()
// Committed SQL dumps (tracked in git).
export const GEAR_DB_SQL_DIR = path.resolve(ROOT, 'tests/fixtures/gear-db')
// Built databases (gitignored disposable cache).
export const GEAR_DB_BUILD_DIR = path.resolve(ROOT, 'tmp/fixtures/gear-db')

// Tables a fixture keeps — exactly the ones the gear importer reads. Everything else in an
// RSL Helper export is account history the app never touches, so it never enters the repo.
export const GEAR_DB_KEPT_TABLES = ['Artifacts', 'InboxArtifacts', 'Champs', 'LastUsedArtifacts']

/**
 * Committed fixture names. `sample*` feed the unit/integration suites; `account-a…d` are
 * four real-world rosters in ascending size, which the WASM memory-fragmentation specs
 * cycle through (re-importing one DB only exercises same-size alloc/free).
 */
export const GEAR_DB_FIXTURES = {
  sample: 'sample',
  sample2: 'sample2',
  sampleSmall: 'sample-small',
  accountA: 'account-a',
  accountB: 'account-b',
  accountC: 'account-c',
  accountD: 'account-d',
}

/** Committed SQL dump path for a fixture name. */
export const gearDbSqlPathFor = (name) => path.join(GEAR_DB_SQL_DIR, `${name}.sql`)

/** Built database path for a fixture name (call `ensureGearDb` before reading it). */
export const gearDbPathFor = (name) => path.join(GEAR_DB_BUILD_DIR, `${name}.db`)

// Double-quote an SQL identifier (table/column names come from sqlite_master, never input).
const quoteIdent = (name) => `"${String(name).replace(/"/g, '""')}"`

// Ordered column names of `table`.
const columnsOf = (db, table) => db.prepare(`PRAGMA table_info(${quoteIdent(table)})`).all().map((c) => c.name)

// Kept tables that exist in `db`, with their original CREATE statements, in kept order.
const keptTablesIn = (db) => GEAR_DB_KEPT_TABLES
  .map((name) => db.prepare("SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name = ?").get(name))
  .filter((row) => row !== undefined)

/**
 * Render the kept tables of `sourcePath` as a deterministic SQL script. Values go through
 * SQLite's own quote(), which keeps each cell's storage class (TEXT stays TEXT even in a
 * REAL column, as RSL Helper writes some lastUse values) and round-trips REALs exactly.
 */
export function renderGearDbSql(sourcePath) {
  const db = new DatabaseSync(sourcePath, { readOnly: true })
  try {
    const lines = [
      '-- RSL Helper gear database fixture: only the tables the gear importer reads.',
      '-- Generated by scripts/test/gear-db-fixtures.mjs (dump); do not edit by hand.',
      'BEGIN;',
    ]
    for (const { name, sql } of keptTablesIn(db)) {
      // Normalize the original CREATE whitespace so re-dumps never churn on formatting.
      lines.push(`${sql.replace(/\s+/g, ' ').trim()};`)
      const cells = columnsOf(db, name).map((c) => `quote(${quoteIdent(c)})`).join(` || ',' || `)
      // rowid order keeps the dump stable and matches the source's natural scan order.
      for (const { v } of db.prepare(`SELECT ${cells} AS v FROM ${quoteIdent(name)} ORDER BY rowid`).all()) {
        lines.push(`INSERT INTO ${quoteIdent(name)} VALUES(${v});`)
      }
    }
    lines.push('COMMIT;', '')
    return lines.join('\n')
  } finally {
    db.close()
  }
}

// Throw unless every kept table of `sourcePath` matches `builtPath` row-for-row and cell-for-cell.
function assertSameKeptTables(sourcePath, builtPath) {
  const db = new DatabaseSync(builtPath)
  try {
    db.prepare('ATTACH DATABASE ? AS src').run(sourcePath)
    for (const { name } of keptTablesIn(db)) {
      const t = quoteIdent(name)
      // EXCEPT both ways compares whole rows; equal counts rule out duplicate-row drift.
      const count = (schema) => db.prepare(`SELECT count(*) AS n FROM ${schema}.${t}`).get().n
      const diff = (a, b) => db.prepare(`SELECT count(*) AS n FROM (SELECT * FROM ${a}.${t} EXCEPT SELECT * FROM ${b}.${t})`).get().n
      if (count('main') !== count('src') || diff('main', 'src') !== 0 || diff('src', 'main') !== 0) {
        throw new Error(`gear-db fixture mismatch in table ${name}: ${builtPath} vs ${sourcePath}`)
      }
    }
  } finally {
    db.close()
  }
}

// Build `name` from its SQL dump into the cache; temp file + rename so readers never see half a DB.
function buildGearDb(name) {
  const target = gearDbPathFor(name)
  fs.mkdirSync(GEAR_DB_BUILD_DIR, { recursive: true })
  const staging = `${target}.${process.pid}.tmp`
  fs.rmSync(staging, { force: true })
  const db = new DatabaseSync(staging)
  try {
    db.exec(fs.readFileSync(gearDbSqlPathFor(name), 'utf8'))
  } finally {
    db.close()
  }
  fs.renameSync(staging, target)
  return target
}

/**
 * Ensure the built database for `name` exists and is not older than its SQL dump; returns
 * its path. Cheap when fresh (two stat calls), so tests can call it unconditionally.
 */
export function ensureGearDb(name) {
  const sqlPath = gearDbSqlPathFor(name)
  if (!fs.existsSync(sqlPath)) throw new Error(`no committed gear-db fixture "${name}": ${sqlPath}`)
  const target = gearDbPathFor(name)
  // A checkout or re-dump touches the .sql, so an mtime comparison catches every change.
  const fresh = fs.existsSync(target) && fs.statSync(target).mtimeMs >= fs.statSync(sqlPath).mtimeMs
  return fresh ? target : buildGearDb(name)
}

/** Ensure every committed fixture is built (run before suites that read them). */
export const ensureAllGearDbs = () => Object.values(GEAR_DB_FIXTURES).map((name) => ensureGearDb(name))

/**
 * Write the dump for `sourcePath` as fixture `name`, rebuild it, and verify it. The dump
 * is taken from an anonymized copy (champion identity removed); the source is never touched.
 */
export function dumpGearDb(sourcePath, name) {
  fs.mkdirSync(GEAR_DB_SQL_DIR, { recursive: true })
  fs.mkdirSync(GEAR_DB_BUILD_DIR, { recursive: true })
  // The copy also frees the source path, so a fixture can be re-dumped from its own build.
  const anonymized = path.join(GEAR_DB_BUILD_DIR, `${name}.${process.pid}.anonymized.db`)
  fs.copyFileSync(sourcePath, anonymized)
  try {
    const champions = anonymizeGearDbChampions(anonymized)
    fs.writeFileSync(gearDbSqlPathFor(name), renderGearDbSql(anonymized))
    assertSameKeptTables(anonymized, buildGearDb(name))
    const kb = (p) => `${Math.round(fs.statSync(p).size / 1024)} KB`
    console.log(`[gear-db-fixtures] ${name}: ${kb(sourcePath)} -> ${kb(gearDbSqlPathFor(name))} SQL, `
      + `${champions} champion(s) anonymized (verified)`)
  } finally {
    fs.rmSync(anonymized, { force: true })
  }
}

// ── CLI ──────────────────────────────────────────────────────────────────────────
// Only act on argv when executed directly; when imported as a library argv belongs to the importer.
const isCliEntry = process.argv[1] !== undefined
  && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
const [, , command, ...args] = isCliEntry ? process.argv : []
if (command === 'dump') {
  if (args.length !== 2) { console.error('usage: gear-db-fixtures.mjs dump <source.db> <name>'); process.exit(2) }
  dumpGearDb(path.resolve(args[0]), args[1])
} else if (command === 'anonymize') {
  // Re-dump committed fixtures from their own builds, e.g. after the anonymizer changed.
  for (const name of args.length > 0 ? args : Object.values(GEAR_DB_FIXTURES)) dumpGearDb(ensureGearDb(name), name)
} else if (command === 'build') {
  for (const p of args.length > 0 ? args.map((n) => ensureGearDb(n)) : ensureAllGearDbs()) console.log(`[gear-db-fixtures] ready ${p}`)
} else if (command !== undefined) {
  console.error(`unknown command "${command}" (expected dump|build|anonymize)`)
  process.exit(2)
}
