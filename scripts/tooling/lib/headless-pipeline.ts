/**
 * headless-pipeline.ts
 *
 * The one place the tooling scripts (and the unit-test wasm warm-up) get what they need to drive
 * the browser-oriented pipeline under plain `node --experimental-wasm-modules`: the `file://`
 * fetch shim wasm-bindgen's loader relies on, the compiled-bindings sync the `tmp/tsc/scripts`
 * output needs, and the SFC / gear-DB loaders that go through the SAME parsers the app uses.
 *
 * Every script used to carry its own copy of these; they drifted (one re-derived the note from
 * the raw JSON and skipped SFC canonicalization, others picked different SFC fields). Import from
 * here instead — SSOT for "make the app's pipeline run headless".
 */
import { cp, mkdir, readFile } from 'node:fs/promises'
import { resolve as resolvePath } from 'node:path'
import { parseSfcObject, type ParsedSfcResult } from '../../../src/lib/sfcIO.js'
import { defaultSubstatTargets } from '../../../src/lib/hsfBuilder.js'
import { importGearDatabaseFromArrayBuffer } from '../../../src/lib/importers/gearDbImporter.js'
import type { NormalizedGearArtifact } from '../../../src/lib/importers/gearDbNormalizer.js'
import { warmupWasmRuleEngine } from '../../../src/lib/wasm/wasmRuleEngine.js'

// Where `tsc -p tsconfig.scripts.json` emits, relative to the repo root; the compiled scripts
// import the wasm bindings by relative path, so the generated files must sit beside them.
const COMPILED_SCRIPTS_DIR = 'tmp/tsc/scripts'
// The wasm-bindgen output the app imports (gitignored; regenerated by `wasm:ensure:rule-engine`).
const GENERATED_WASM_DIR = 'src/lib/wasm/generated'

/**
 * Teach Node's `fetch` to serve `file://` URLs. wasm-bindgen's loader resolves the generated
 * `.wasm` beside its JS as a `file://` URL and fetches it; Node's fetch does not handle that
 * scheme, so intercept it and hand back the bytes with the wasm MIME type. Everything else is
 * delegated to the original fetch. Safe to call more than once and outside Node (no-op there).
 */
export const installNodeFileFetch = async (): Promise<void> => {
  const isNodeRuntime = typeof process !== 'undefined' && Boolean(process.versions?.node)
  if (!isNodeRuntime) return
  const originalFetch = globalThis.fetch
  if (typeof originalFetch !== 'function') return
  globalThis.fetch = (async (input: RequestInfo | URL, init?: RequestInit): Promise<Response> => {
    // Normalize Request | string | URL into a raw URL string once.
    const url = typeof input === 'string' ? input : (input instanceof URL ? input.href : input.url)
    if (url.startsWith('file://')) {
      const bytes = await readFile(new URL(url))
      return new Response(new Uint8Array(bytes), {
        status: 200,
        headers: { 'content-type': 'application/wasm' },
      })
    }
    return originalFetch(input, init)
  }) as typeof fetch
}

/**
 * Copy the generated wasm bindings next to the compiled scripts so their relative imports
 * resolve. Non-fatal on failure: warm-up then surfaces a clear wasm error instead.
 */
export const syncCompiledWasmBindings = async (): Promise<void> => {
  const root = process.cwd()
  const targetDir = resolvePath(root, COMPILED_SCRIPTS_DIR, GENERATED_WASM_DIR)
  try {
    await mkdir(targetDir, { recursive: true })
    await cp(resolvePath(root, GENERATED_WASM_DIR), targetDir, { recursive: true, force: true })
  } catch {
    // Keep tooling resilient: warm-up reports the missing module if the copy failed.
  }
}

/** The three steps every headless script runs before touching the rule engine, in order. */
export const prepareHeadlessRuleEngine = async (): Promise<void> => {
  await installNodeFileFetch()
  await syncCompiledWasmBindings()
  await warmupWasmRuleEngine()
}

/**
 * Parse an SFC file exactly as the app does — including the note's legacy-marker
 * canonicalization and migrations — so a script never applies overrides against a note the app
 * itself would not use. Callers pick the fields they need off the parsed object.
 */
export const loadSfc = async (sfcPath: string): Promise<ParsedSfcResult> => {
  const parsed = JSON.parse(await readFile(sfcPath, 'utf8')) as unknown
  return parseSfcObject(parsed, { metasets: [], substatTargets: defaultSubstatTargets() })
}

/** Import an RSL Helper gear DB through the app's importer; inbox pieces included. */
export const loadGear = async (dbPath: string): Promise<NormalizedGearArtifact[]> => {
  const buffer = await readFile(dbPath)
  const arrayBuffer = buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength)
  const imported = await importGearDatabaseFromArrayBuffer(arrayBuffer)
  return [...imported.artifacts, ...imported.inboxArtifacts]
}
