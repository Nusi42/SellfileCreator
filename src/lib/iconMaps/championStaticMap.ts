/**
 * championStaticMap
 *
 * Static, build-time fallback for champion intrinsics keyed by `BaseHeroID`
 * (= `floor(typeId / 10) * 10`). Rarity and affinity are intrinsic to a champion
 * type, so they can be resolved from the type id alone when the live feed omits them.
 *
 * WHY: RSL Helper's WebSocket `champions` push dropped the `Rarity`, `Affinity` and
 * `Name` fields. On a cold start with Helper already running there is no prior snapshot
 * to merge from, so champion icons rendered with no rarity colour. This map is the
 * fallback consulted by `championRowToLookupRecord` when those fields are absent.
 *
 * SSOT / PROVENANCE: generated from the RSL Helper SQLite DBs under `examples/`
 * (Champs table, aggregated across all accounts). Rarity is intrinsic to a champion type —
 * verified stable per BaseHeroID across every DB (the only "conflicts" were stray
 * `Rarity = 0` rows, ignored); affinity had zero conflicts. Mixed-locale DBs meant a
 * handful of German-only names were replaced with their official English forms (verified
 * via AyumiLove / HellHades); curly apostrophes (`’`, e.g. Krok’mar) are the real spelling.
 *
 * ENCODING — rarity 1..6 = Common, Uncommon, Rare, Epic, Legendary, Mythical;
 *            affinity 1..4 = Magic, Force, Spirit, Void.
 *
 * Live payload values always win; this only fills gaps. Do not hand-edit individual rows —
 * regenerate from the source DBs so the data stays consistent. When the dev-only
 * `[champion-static]` log in gearDbLookups.ts reports a baseHeroId missing here, that
 * champion is newer than the source DBs and can be added on the next regeneration.
 */
